import {Router} from 'express';
import {protect,optionalAuth} from '../middlewares/auth.middleware.js';
import {rateLimit} from '../middlewares/rateLimit.middleware.js';
import {asyncHandler} from '../utils/asyncHandler.js';
import {ApiResponse} from '../utils/apiResponse.js';
import {text} from '../utils/validation.js';
import {SearchHistory} from '../models/index.js';
import * as catalog from '../services/catalogBrowse.service.js';
import * as playlist from '../services/playlist.service.js';
import * as library from '../services/library.service.js';
import * as playback from '../services/playback.service.js';
import * as profile from '../services/profile.service.js';
import * as charts from '../services/charts.service.js';
import {submitReport} from '../services/moderation.service.js';
import {receivePlaylistCover} from '../middlewares/upload.middleware.js';
import {cleanupUploads} from '../services/adminUpload.service.js';
export const respond=(work,status=200)=>asyncHandler(async(req,res)=>res.status(status).json(new ApiResponse(status,await work(req),'Thành công.')));
const router=Router();
router.get('/capabilities',respond(()=>({playlist:true,library:true,playback:true,search:true,catalog_browse:true,moderation:true,hum_search:false,assistant:false,audio_recommendations:false,email_recovery:false,mood_recuration:false,spatial_processing:false,vocal_separation:false})));
router.get('/artists',respond(r=>catalog.listEntities('artist',r.query)));
router.get('/artists/:id',respond(r=>catalog.artistDetail(r.params.id)));
router.get('/artists/:id/top-tracks',respond(r=>catalog.artistTracks(r.params.id)));
router.post('/artists/:id/follow',protect,respond(r=>library.followArtist(r.user,r.params.id)));
router.put('/artists/:id/follow',protect,respond(r=>library.followArtist(r.user,r.params.id,true)));
router.delete('/artists/:id/follow',protect,respond(r=>library.followArtist(r.user,r.params.id,false)));
router.get('/albums',respond(r=>catalog.listEntities('album',r.query)));
router.get('/albums/:id',respond(r=>catalog.albumDetail(r.params.id)));
router.get('/genres',respond(()=>catalog.genres()));
router.get('/charts/vn',respond(r=>charts.chart('VN',r.query)));
router.get('/charts/global',respond(r=>charts.chart('INTL',r.query)));
router.get('/charts/spotlight',respond(()=>charts.spotlight()));
router.get('/charts/genres/:slug',respond(r=>catalog.genreTracks(r.params.slug,r.query)));
router.get('/search/suggestions',respond(r=>catalog.suggestions(r.query)));
router.get('/search/history',protect,respond(r=>SearchHistory.find({user_id:r.user._id}).sort({searched_at:-1,_id:-1}).limit(15).select('keyword searched_at').lean()));
router.delete('/search/history',protect,respond(async r=>{const filter={user_id:r.user._id};if(r.query.keyword!==undefined)filter.normalized=text(r.query.keyword,'keyword',{max:200}).normalize('NFC').toLowerCase();await SearchHistory.deleteMany(filter);return null;}));
router.get('/search',optionalAuth,respond(r=>catalog.search(r.query,r.user)));
router.post('/playlists',protect,respond(r=>playlist.createPlaylist(r.user,r.body),201));
router.get('/playlists/:id',optionalAuth,respond(r=>playlist.playlistDetail(r.params.id,r.user,r.query)));
router.patch('/playlists/:id',protect,receivePlaylistCover,respond(async r=>{try{return await playlist.mutatePlaylist(r.user,r.params.id,'update',r.body,{cover:r.file});}catch(e){await cleanupUploads({cover:r.file?[r.file]:[]});throw e;}}));
router.delete('/playlists/:id',protect,respond(r=>playlist.mutatePlaylist(r.user,r.params.id,'delete')));
router.post('/playlists/:id/tracks',protect,respond(r=>playlist.mutatePlaylist(r.user,r.params.id,'add',r.body)));
router.delete('/playlists/:id/tracks/:songId',protect,respond(r=>playlist.mutatePlaylist(r.user,r.params.id,'remove',{...r.body,song_id:r.params.songId})));
router.put('/playlists/:id/reorder',protect,respond(r=>playlist.mutatePlaylist(r.user,r.params.id,'reorder',r.body)));
router.get('/library/overview',protect,respond(r=>library.libraryOverview(r.user)));
router.get('/library/liked-songs',protect,respond(r=>library.likedSongs(r.user,r.query)));
router.get('/library/following-artists',protect,respond(r=>library.followingArtists(r.user,r.query)));
router.get('/library/playlists',protect,respond(r=>playlist.listPlaylists(r.user,r.query)));
// Heartbeats are independently bounded; normal API limit must not interrupt playback.
router.post('/playback/events',protect,rateLimit({limit:300}),respond(r=>playback.recordEvent(r.user,r.auth.sessionId,r.body)));
router.get('/playback/history',protect,respond(r=>playback.history(r.user,r.query)));
router.get('/playback/queue',protect,respond(r=>playback.getQueue(r.user)));
router.put('/playback/queue',protect,respond(r=>playback.setQueue(r.user,r.body)));
router.get('/users/stats',protect,respond(r=>profile.stats(r.user)));
router.get('/users/acoustic-settings',protect,respond(r=>profile.getSettings(r.user)));
router.patch('/users/acoustic-settings',protect,respond(r=>profile.updateSettings(r.user,r.body)));
router.post('/songs/:id/reports',protect,rateLimit({limit:5}),respond(r=>submitReport(r.user,r.params.id,r.body),201));
export default router;
