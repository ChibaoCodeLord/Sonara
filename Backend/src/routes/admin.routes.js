import {Router} from 'express';
import {protect,restrictTo} from '../middlewares/auth.middleware.js';
import {receiveTrackUpload,receivePlaylistCover} from '../middlewares/upload.middleware.js';
import {createTrack} from '../controllers/admin.controller.js';
import * as moderation from '../services/moderation.service.js';
import {respond} from './core.routes.js';
import {asyncHandler} from '../utils/asyncHandler.js';
import {rateLimit} from '../middlewares/rateLimit.middleware.js';
import * as session from '../services/adminSession.service.js';
import * as read from '../services/adminRead.service.js';
import * as entities from '../services/adminEntities.service.js';
import * as users from '../services/adminUsers.service.js';
import * as ops from '../services/adminOps.service.js';
import {previewSession,streamPreview} from '../services/adminMedia.service.js';
import {inspectCover} from '../services/adminMetadata.service.js';
import {cleanupUploads} from '../services/adminUpload.service.js';
const router=Router();
router.post('/session',session.adminClient,rateLimit({limit:5,failedOnly:true}),asyncHandler(async(req,res)=>res.json({data:await session.loginAdmin(req,res)})));
router.post('/session/refresh',session.adminClient,rateLimit({limit:60}),asyncHandler(async(req,res)=>res.json({data:await session.refreshAdmin(req,res)})));
router.post('/session/logout',session.adminClient,asyncHandler(async(req,res)=>res.json({data:await session.logoutAdmin(req,res)})));
router.get('/media/:token',rateLimit({limit:300}),asyncHandler(streamPreview));
router.use(protect,restrictTo('admin'));
router.get('/overview',respond(r=>read.overview(r.query)));
router.get('/songs',respond(r=>read.songs(r.query)));
router.get('/songs/:id',respond(r=>read.songDetail(r.params.id)));
router.post('/songs',receiveTrackUpload,createTrack);
router.patch('/songs/:id',receivePlaylistCover,respond(async r=>{const files={cover:r.file?[r.file]:[]};try{if(['true','false'].includes(r.body.explicit))r.body.explicit=r.body.explicit==='true';const coverUrl=await inspectCover(files);return await moderation.editTrack(r.user,r.params.id,r.body,false,{coverUrl});}catch(e){await cleanupUploads(files);throw e;}}));
router.delete('/songs/:id',respond(r=>moderation.editTrack(r.user,r.params.id,r.body||{},true)));
router.post('/songs/:id/preview-session',respond(r=>previewSession(r.user,r.auth.sessionId,r.params.id)));
router.get('/reports',respond(r=>moderation.reports(r.query)));
router.get('/reports/:id',respond(r=>read.reportDetail(r.params.id)));
router.patch('/reports/:id',respond(r=>moderation.resolveReport(r.user,r.params.id,r.body)));
router.get('/audit-logs',respond(r=>moderation.auditLogs(r.query)));
for(const [path,kind]of [['artists','artist'],['albums','album']]){
  router.get('/'+path,respond(r=>entities.entities(kind,r.query)));
  router.post('/'+path,respond(r=>entities.editEntity(r.user,kind,null,r.body),201));
  router.get('/'+path+'/:id',respond(r=>entities.entityDetail(kind,r.params.id,r.query)));
  router.patch('/'+path+'/:id',respond(r=>entities.editEntity(r.user,kind,r.params.id,r.body)));
}
router.get('/genres',respond(()=>entities.genreList()));
router.post('/genres',respond(r=>entities.editGenre(r.user,null,r.body),201));
router.patch('/genres/:slug',respond(r=>entities.editGenre(r.user,r.params.slug,r.body)));
router.get('/users',respond(r=>users.users(r.query)));
router.get('/users/:id',respond(r=>users.userDetail(r.params.id)));
router.patch('/users/:id',respond(r=>users.mutateUser(r.user,r.params.id,r.body)));
router.post('/users/:id/revoke-sessions',respond(r=>users.mutateUser(r.user,r.params.id,r.body,true)));
router.get('/ingestion',respond(()=>ops.ingestion()));
router.get('/audio-audits',respond(()=>ops.audits()));
router.post('/audio-audits',rateLimit({limit:5}),respond(r=>ops.startAudit(r.user,r.body),202));
router.get('/audio-audits/:id',respond(r=>ops.auditDetail(r.params.id)));
router.get('/system',respond(()=>ops.system()));
export default router;
