import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import {ENV} from './config/env.js';
import {ApiError} from './utils/apiError.js';
import {errorHandler} from './middlewares/error.middleware.js';
import {rateLimit} from './middlewares/rateLimit.middleware.js';
import rootRouter from './routes/index.js';
import uploadRoutes from './routes/uploads.routes.js';
const app=express();
if(ENV.TRUST_PROXY)app.set('trust proxy',ENV.TRUST_PROXY);
app.use(helmet({crossOriginResourcePolicy:false}));
app.use(cors({origin:ENV.CORS_ORIGIN,credentials:ENV.CORS_ORIGIN!=='*'}));
app.use(express.json({limit:'256kb'}));
app.use(express.urlencoded({extended:false,limit:'256kb'}));
if(ENV.NODE_ENV==='development')app.use(morgan('dev',{skip:req=>req.path.startsWith('/api/v1/admin/media/')}));
app.use('/uploads',uploadRoutes);
app.use('/api/v1',rateLimit({limit:ENV.API_RATE_LIMIT,skip:req=>['/health','/live','/ready','/playback/events'].includes(req.path)||req.path.endsWith('/stream')||req.path.startsWith('/catalog/local-audio/')||req.path.startsWith('/admin/media/')}),rootRouter);
app.all('*',(req,_res,next)=>next(new ApiError(404,`Không tìm thấy endpoint: ${req.method} ${req.path}`)));
app.use(errorHandler);
export default app;
